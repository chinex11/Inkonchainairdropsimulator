'use strict';
const H = 'https://ink.easscan.org/graphql';
const gql = async (query, variables) => { const r = await fetch(H, { method: 'POST', headers: { 'content-type': 'application/json', 'User-Agent': 'Mozilla/5.0' }, body: JSON.stringify({ query, variables }) }); const t = await r.text(); try { return JSON.parse(t); } catch (e) { return { raw: t.slice(0, 300) }; } };
(async () => {
  const s = await gql('{schemas(take:100, orderBy:[{time:desc}]){id index schema creator resolver revocable time}}');
  const list = (s.data && s.data.schemas) || [];
  console.log('schemas returned', list.length, s.errors ? JSON.stringify(s.errors).slice(0, 200) : '');
  list.forEach((x) => console.log(' ', x.index, x.id.slice(0, 12), '|', x.schema.slice(0, 90), '| creator', x.creator, '| resolver', x.resolver));
  const a = await gql('{attestations(take:40, orderBy:[{time:desc}]){id schemaId attester recipient revoked time decodedDataJson}}');
  const at = (a.data && a.data.attestations) || [];
  console.log('\nrecent attestations', at.length, a.errors ? JSON.stringify(a.errors).slice(0, 200) : '');
  const by = {};
  at.forEach((x) => { const k = x.schemaId + ' / ' + x.attester; by[k] = (by[k] || 0) + 1; });
  console.log('by schema/attester:', JSON.stringify(by, null, 1));
  at.slice(0, 4).forEach((x) => console.log(' sample', x.recipient, x.schemaId.slice(0, 12), x.decodedDataJson.slice(0, 160)));
  const agg = await gql('{aggregateAttestation{_count{_all}}}');
  console.log('\ntotal attestations on Ink', JSON.stringify(agg.data || agg));
  const kr = await gql('{schemas(take:50, where:{schema:{contains:"kraken", mode:insensitive}}){id schema creator}}');
  console.log('schemas containing kraken', JSON.stringify(kr.data || kr).slice(0, 500));
  const ver = await gql('{schemas(take:50, where:{schema:{contains:"verif", mode:insensitive}}){id schema creator}}');
  console.log('schemas containing verif', JSON.stringify(ver.data || ver).slice(0, 1200));
})().catch((e) => { console.error('ERROR', e.message); process.exit(1); });
